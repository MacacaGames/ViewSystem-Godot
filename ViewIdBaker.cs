using System;
using System.Linq;
using System.Text;
using System.Collections.Generic;
namespace MacacaGames.ViewSystem;

public static class ViewIdBaker
{
    public static string Generate(ViewCatalog catalog,string className="ViewIds")
    {
        catalog.Validate();
        var text=new StringBuilder("// Generated by ViewSystem.\nnamespace MacacaGames.ViewSystem.Generated;\npublic static class ").Append(Identifier(className)).Append("\n{\n");
        foreach(var kind in Enum.GetValues<ViewKind>())
        {
            text.Append("    public static class ").Append(kind).Append("s\n    {\n");
            var names=new HashSet<string>(StringComparer.Ordinal);
            foreach(var entry in catalog.Entries.Where(e=>e.Kind==kind))
            {
                string name=Identifier(entry.Id);
                if(!names.Add(name))throw new InvalidOperationException("IDs collide as C# identifiers: "+entry.Id);
                text.Append("        public const string ").Append(name).Append(" = \"").Append(Escape(entry.Id)).Append("\";\n");
            }
            text.Append("    }\n");
        }
        return text.Append("}\n").ToString();
    }
    private static string Identifier(string value)
    {string name=new string(value.Select(c=>char.IsAsciiLetterOrDigit(c)||c=='_'?c:'_').ToArray());if(name.Length==0)name="_";if(char.IsAsciiDigit(name[0]))name="_"+name;return "@"+name;}
    private static string Escape(string value)=>string.Concat(value.Select(c=>c switch {'\\'=>"\\\\",'\"'=>"\\\"",'\n'=>"\\n",'\r'=>"\\r",'\t'=>"\\t",_=>char.IsControl(c)?"\\u"+((int)c).ToString("x4"):c.ToString()}));
}
